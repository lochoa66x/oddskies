export function scoreRawSource(rawSource, options = {}) {
  const rawText = cleanText(rawSource.raw_text);
  const rawTitle = cleanText(rawSource.raw_title);
  const joinedText = [rawTitle, rawText, cleanText(rawSource.location_hint)]
    .filter(Boolean)
    .join(" ");
  const normalizedSearchText = normalizeForSearch(joinedText);
  const reasons = [];
  let score = 0;

  const location = extractLocation(rawSource, joinedText, normalizedSearchText);
  const timeHint = extractTimeHint(joinedText);
  const hasMediaHint = Boolean(
    cleanText(rawSource.raw_media_url) ||
      /\b(photo|video|image|picture|clip|recorded|filmed|camera)\b/i.test(joinedText),
  );
  const hasSourceUrl = Boolean(cleanText(rawSource.source_url));
  const hasAuthor = Boolean(cleanText(rawSource.author_handle));
  const hasPostedAt = Boolean(cleanText(rawSource.posted_at));
  const hasCategory = cleanText(rawSource.category_guess) !== "Unknown";
  const possibleJoke = JOKE_PATTERNS.some((pattern) => pattern.test(joinedText));
  const possibleAiGenerated = AI_PATTERNS.some((pattern) => pattern.test(joinedText));
  const possiblePrivateLocation = PRIVATE_LOCATION_PATTERNS.some((pattern) =>
    pattern.test(joinedText),
  );
  const hasHarassmentLanguage = HARASSMENT_PATTERNS.some((pattern) =>
    pattern.test(joinedText),
  );
  const possibleDuplicate = Boolean(options.possibleDuplicate);

  if (hasSourceUrl) {
    score += 20;
    reasons.push("Source URL captured");
  } else {
    score -= 10;
    reasons.push("Missing source URL");
  }

  if (rawText.length > 80) {
    score += 15;
    reasons.push("Enough raw text for review");
  }

  if (rawText.length > 180) {
    score += 10;
    reasons.push("Rich source text");
  }

  if (rawText.length < 40) {
    score -= 25;
    reasons.push("Very short raw text");
  }

  if (location.hasLocationHint) {
    score += 15;
    reasons.push("Location hint found");
  } else {
    score -= 10;
    reasons.push("No location hint");
  }

  if (timeHint.hasTimeHint) {
    score += 10;
    reasons.push("Time hint found");
  } else {
    score -= 10;
    reasons.push("No time hint");
  }

  if (hasMediaHint) {
    score += 10;
    reasons.push("Media hint found");
  }

  if (hasCategory) {
    score += 10;
    reasons.push("Category guess available");
  } else {
    score -= 15;
    reasons.push("Category guess is Unknown");
  }

  if (REPORT_LANGUAGE_PATTERN.test(joinedText)) {
    score += 10;
    reasons.push("Report-like language");
  }

  if (hasAuthor) {
    score += 5;
    reasons.push("Author handle captured");
  }

  if (hasPostedAt) {
    score += 5;
    reasons.push("Posted date captured");
  }

  if (possibleJoke) {
    score -= 20;
    reasons.push("Possible joke or meme language");
  }

  if (possibleAiGenerated) {
    reasons.push("Possible AI-generated or edited media mention");
  }

  if (possiblePrivateLocation) {
    score -= 25;
    reasons.push("Private-looking contact or address detail");
  }

  if (hasHarassmentLanguage) {
    score -= 15;
    reasons.push("Possible targeting language");
  }

  if (possibleDuplicate) {
    score -= 20;
    reasons.push("Possible duplicate source");
  }

  const curationScore = clampScore(score);

  return {
    curation_label: labelForScore(curationScore),
    curation_reasons: Array.from(new Set(reasons)),
    curation_score: curationScore,
    extracted_country_guess: location.extractedCountryGuess,
    extracted_event_datetime_text: timeHint.extractedEventDatetimeText,
    extracted_location_text: possiblePrivateLocation
      ? null
      : location.extractedLocationText,
    extracted_region_guess: location.extractedRegionGuess,
    has_location_hint: location.hasLocationHint,
    has_media_hint: hasMediaHint,
    has_time_hint: timeHint.hasTimeHint,
    last_scored_at: new Date().toISOString(),
    normalized_summary: makeSummary(rawText),
    normalized_title: makeTitle(rawTitle || rawText),
    possible_ai_generated: possibleAiGenerated,
    possible_duplicate: possibleDuplicate,
    possible_joke: possibleJoke,
    possible_private_location: possiblePrivateLocation,
  };
}

function extractLocation(rawSource, joinedText, normalizedSearchText) {
  const existingHint = cleanText(rawSource.location_hint);

  if (existingHint) {
    return {
      extractedCountryGuess: null,
      extractedLocationText: existingHint,
      extractedRegionGuess: null,
      hasLocationHint: true,
    };
  }

  for (const [keyword, region, country] of LOCATION_KEYWORDS) {
    if (normalizedSearchText.includes(keyword)) {
      return {
        extractedCountryGuess: country,
        extractedLocationText: titleCase(keyword),
        extractedRegionGuess: region,
        hasLocationHint: true,
      };
    }
  }

  const patternMatch = joinedText.match(LOCATION_PATTERN);

  if (patternMatch?.[1]) {
    return {
      extractedCountryGuess: null,
      extractedLocationText: patternMatch[1].trim(),
      extractedRegionGuess: null,
      hasLocationHint: true,
    };
  }

  return {
    extractedCountryGuess: null,
    extractedLocationText: null,
    extractedRegionGuess: null,
    hasLocationHint: false,
  };
}

function extractTimeHint(text) {
  for (const pattern of TIME_PATTERNS) {
    const match = text.match(pattern);

    if (match?.[0]) {
      return {
        extractedEventDatetimeText: match[0],
        hasTimeHint: true,
      };
    }
  }

  return {
    extractedEventDatetimeText: null,
    hasTimeHint: false,
  };
}

function labelForScore(score) {
  if (score >= 75) {
    return "Strong candidate";
  }

  if (score >= 50) {
    return "Good candidate";
  }

  if (score >= 25) {
    return "Needs review";
  }

  return "Low context";
}

function makeTitle(text) {
  const compact = cleanText(text);

  if (!compact) {
    return null;
  }

  return compact.length > 90 ? `${compact.slice(0, 87).trim()}...` : compact;
}

function makeSummary(text) {
  const compact = cleanText(text);

  if (!compact) {
    return null;
  }

  return compact.length > 260 ? `${compact.slice(0, 257).trim()}...` : compact;
}

function titleCase(value) {
  return value
    .split(/\s+/)
    .map((part) => `${part.slice(0, 1).toUpperCase()}${part.slice(1)}`)
    .join(" ");
}

function normalizeForSearch(value) {
  return cleanText(value)
    .normalize("NFD")
    .replace(/\p{Diacritic}/gu, "")
    .toLowerCase();
}

function cleanText(value) {
  return typeof value === "string" ? value.replace(/\s+/g, " ").trim() : "";
}

function clampScore(score) {
  return Math.max(0, Math.min(100, Math.round(score)));
}
